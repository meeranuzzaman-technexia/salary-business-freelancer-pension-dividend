const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const assert = require('node:assert/strict');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(r, ...rest) { return resolve.call(this, r.startsWith('@/') ? path.join(root,r.slice(2)) : r, ...rest); };
Module._extensions['.ts'] = (m,f) => m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,f);
const {sanitizeBusinessActivities} = require('../lib/tax/business-activity.ts');
const {resolveTy2026IncomeSelections,TY2026_BUSINESS_PROFIT_SUBCATEGORY} = require('../lib/tax/rules/ty2026/subcategories.ts');
assert.deepEqual(sanitizeBusinessActivities(['trading','services','trading']),['trading','services']);
assert.equal(sanitizeBusinessActivities(['invented']),null);
assert.equal(sanitizeBusinessActivities('trading'),null);
const result=resolveTy2026IncomeSelections({incomeSources:['business'],selections:[{source:'business',subcategory:TY2026_BUSINESS_PROFIT_SUBCATEGORY,details:{businessActivities:['trading','services']}}],requireComplete:true});
assert.equal(result.success,true);
assert.deepEqual(result.selections[0].details.businessActivities,['trading','services']);
const wizard=fs.readFileSync(path.join(root,'components/tax/filing/filing-wizard.tsx'),'utf8');
assert.match(wizard,/"documents",\s*\.\.\.\(isMyself && taxYear === 2026/);
assert.match(wizard,/business_review:.*businessIntakeLoadedFor.*WizardBusinessProfitStep/);
assert.match(wizard,/navigationStepKey === "documents" && intakeReady \? 2 : 1/);
assert.match(wizard,/getBusinessDocumentIntakeAction/);
assert.ok(wizard.includes('<WizardBusinessActivityStep'));
